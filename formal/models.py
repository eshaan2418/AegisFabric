"""Model registry for TLC: every (spec, variant, bounds) we check, and the result we expect.

`python -m formal.models` regenerates the .cfg files; `formal/check.sh` / `formal.run_tlc` runs them.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

FORMAL = Path(__file__).resolve().parent


@dataclass
class Model:
    name: str
    dir: str  # subdirectory of formal/ holding the spec and MC.tla
    constants: dict[str, str]
    invariants: list[str]
    properties: list[str] = field(default_factory=list)
    expect: str = "pass"  # "pass" or "violation"
    small: bool = True  # included in the pytest run
    note: str = ""

    @property
    def cfg(self) -> Path:
        return FORMAL / self.dir / f"{self.name}.cfg"

    def render(self) -> str:
        lines = [f"\\* generated by formal/models.py -- {self.note}", "CONSTANTS"]
        lines += [f"  {k} {'<-' if v.startswith('MC') else '='} {v}" for k, v in self.constants.items()]
        lines += ["SPECIFICATION Spec", "INVARIANTS " + " ".join(self.invariants)]
        if self.properties:
            lines.append("PROPERTIES " + " ".join(self.properties))
        lines.append("CHECK_DEADLOCK FALSE")
        return "\n".join(lines) + "\n"


def _p1(
    name,
    *,
    bug_idx=False,
    bug_gc=False,
    touch=True,
    live_pending=True,
    crash=1,
    gc=1,
    k=1,
    expect="pass",
    props=True,
    small=True,
    note="",
    invariants=None,
):
    b = lambda x: "TRUE" if x else "FALSE"  # noqa: E731
    return Model(
        name=name,
        dir="ckpt",
        constants={
            "Chunks": '{"c1", "c2", "c3"}',
            "Mans": '{"m1", "m2"}',
            "Refs": "MCRefs",
            "K": str(k),
            "MaxCrash": str(crash),
            "MaxGC": str(gc),
            "BugIndexBeforeFsync": b(bug_idx),
            "BugGcIgnoreEpoch": b(bug_gc),
            "FixTouch": b(touch),
            "FixLivePending": b(live_pending),
        },
        invariants=invariants or ["TypeOK", "I1", "I2", "I3", "AckedDurable"],
        properties=["AllDone"] if props else [],
        expect=expect,
        small=small,
        note=note,
    )


def _p3(
    name,
    *,
    renew_div=2,
    backdate="2*S",
    wait_remove=True,
    wait_bundle=True,
    fails=1,
    expect="pass",
    small=True,
    note="",
    horizon=26,
    invariants=None,
    t=10,
):
    b = lambda x: "TRUE" if x else "FALSE"  # noqa: E731
    return Model(
        name=name,
        dir="rotation",
        constants={
            "Verifiers": '{"v1", "v2"}',
            "T": str(t),
            "S": "1",
            "Lmax": "1",
            "R": "1",
            "MaxFail": str(fails),
            "Horizon": str(horizon),
            "RenewDiv": str(renew_div),
            "Backdate": "MCBackdate2S" if backdate == "2*S" else "MCBackdateS",
            "WaitBeforeRemove": b(wait_remove),
            "WaitBundleBeforeSign": b(wait_bundle),
        },
        invariants=invariants or ["TypeOK", "R1"],
        expect=expect,
        small=small,
        note=note,
    )


