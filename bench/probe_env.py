"""Probe host + lab-container environment and write ENVIRONMENT.md and results/m0/environment.json.

Usage: uv run python -m bench.probe_env
"""

from __future__ import annotations

import json
import os
import platform
import shutil
import subprocess

from bench.meta import REPO_ROOT, write_result

LAB_PROBE = r"""
set +e
echo "kernel=$(uname -r)"
echo "nproc=$(nproc)"
echo "mem_kb=$(grep MemTotal /proc/meminfo | awk '{print $2}')"
echo "io_uring_disabled=$(cat /proc/sys/kernel/io_uring_disabled 2>/dev/null || echo missing)"
ip netns add probe_ns >/dev/null 2>&1 && echo netns=ok && ip netns del probe_ns || echo netns=fail
ip link add pv0 type veth peer name pv1 >/dev/null 2>&1 && tc qdisc add dev pv0 root netem delay 1ms >/dev/null 2>&1 && echo netem=ok || echo netem=fail
tc qdisc add dev pv1 root tbf rate 10mbit burst 32kbit latency 50ms >/dev/null 2>&1 && echo tbf=ok || echo tbf=fail
ip link del pv0 >/dev/null 2>&1
grep -q xfs /proc/filesystems && echo xfs=ok || echo xfs=fail
grep -q ext4 /proc/filesystems && echo ext4=ok || echo ext4=fail
modprobe openvswitch >/dev/null 2>&1; [ -d /sys/module/openvswitch ] && echo ovs_kmod=ok || echo ovs_kmod=missing
[ -e /dev/fuse ] && echo fuse=ok || echo fuse=missing
echo frr=$(dpkg-query -W -f='${Version}' frr 2>/dev/null || echo missing)
python3 -c 'import torch;print("torch="+torch.__version__)' 2>/dev/null
lsblk -d -o NAME,ROTA,SIZE 2>/dev/null | grep -E '^vd|^nvme|^sd' | tr -s ' ' | tr '\n' ';' | sed 's/^/blk=/'; echo
"""


def sh(cmd: list[str], timeout: int = 60) -> str:
    try:
        return subprocess.run(cmd, capture_output=True, text=True, timeout=timeout).stdout.strip()
    except Exception as e:  # pragma: no cover - environment dependent
        return f"ERROR: {e}"


def host_info() -> dict:
    info = {
        "os": platform.platform(),
        "machine": platform.machine(),
        "python": platform.python_version(),
    }
    if platform.system() == "Darwin":
        info["cpu"] = sh(["sysctl", "-n", "machdep.cpu.brand_string"])
        info["cores"] = int(sh(["sysctl", "-n", "hw.ncpu"]) or 0)
        info["mem_gb"] = round(int(sh(["sysctl", "-n", "hw.memsize"]) or 0) / 2**30, 1)
        gpu = sh(["system_profiler", "SPDisplaysDataType"])
        info["gpu"] = " ".join(
            line.strip() for line in gpu.splitlines() if "Chipset" in line or "Cores" in line
        )
    try:
        import torch

        info["torch"] = torch.__version__
        info["cuda"] = torch.cuda.is_available()
        info["mps"] = torch.backends.mps.is_available()
        info["gloo"] = torch.distributed.is_gloo_available()
        info["nccl"] = torch.distributed.is_nccl_available()
    except Exception as e:
        info["torch"] = f"unavailable: {e}"
    du = shutil.disk_usage(REPO_ROOT)
    info["disk_free_gb"] = round(du.free / 2**30, 1)
    path = os.environ.get("PATH", "") + os.pathsep + os.path.expanduser("~/.cargo/bin")
    info["tools"] = {
        t: bool(shutil.which(t, path=path))
        for t in ["docker", "cargo", "java", "ffmpeg", "tectonic", "uv", "git"]
    }
    info["sudo_passwordless"] = subprocess.run(["sudo", "-n", "true"], capture_output=True).returncode == 0
    return info


def lab_info(image: str) -> dict:
    if not shutil.which("docker"):
        return {"available": False}
    out = sh(["docker", "run", "--rm", "--privileged", image, "bash", "-c", LAB_PROBE], timeout=120)
    kv = {}
    for line in out.splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            kv[k.strip()] = v.strip()
    kv["image"] = image
    kv["available"] = "kernel" in kv
    return kv


def choose_rung(host: dict, lab: dict) -> str:
    if host.get("cuda"):
        return "gpu"
    return "cpu"


def main() -> None:
    import argparse

    ap = argparse.ArgumentParser()
    ap.add_argument("--image", default="aegis-lab:latest")
    args = ap.parse_args()
    host = host_info()
    lab = lab_info(args.image)
    rung = choose_rung(host, lab)
    write_result("m0/environment.json", {"host": host, "lab": lab, "rung": rung})

    md = [
        "# ENVIRONMENT",
        "",
        "Generated by `uv run python -m bench.probe_env` (raw: `results/m0/environment.json`).",
        "",
    ]
    md += ["## Host", ""] + [f"- **{k}**: {v}" for k, v in host.items()] + [""]
    md += ["## Lab container (privileged Linux, Docker Desktop VM)", ""] + [
        f"- **{k}**: {v}" for k, v in lab.items()
    ]
    md += [
        "",
        "## Chosen fallback rung",
        "",
        f"**{rung.upper()}-only rung.** No CUDA device is present (Apple-silicon GPU via MPS only; no NCCL, no "
        "multi-process collectives on MPS). Training uses a tiny transformer with `torchrun`-style multi-process "
        "Gloo, one rank per network namespace, so every collective crosses the emulated WAN. See DECISIONS.md D-002.",
        "",
    ]
    (REPO_ROOT / "ENVIRONMENT.md").write_text("\n".join(md))
    print(json.dumps({"rung": rung, "lab_available": lab.get("available")}, indent=2))


if __name__ == "__main__":
    main()
