"""Registry of every number quoted in the write-up, each computed from a named result file.

    python -m bench.claims            # → results/claims.json and paper/numbers.tex

A claim is (id, source file under results/, function of that file's JSON → number, format). The paper uses
the generated macros (\\C<id>), so it contains no hand-typed results. README / RESUME_BULLETS / FINAL_REVIEW
quote the formatted text, and `bench.audit_numbers` checks every number in those documents against the set
of claims (not against arbitrary values found anywhere in results/). Claims whose source file is missing are
reported and skipped, never guessed.
"""

from __future__ import annotations

import dataclasses
import json
import re
from collections.abc import Callable
from typing import Any

from bench.meta import REPO_ROOT, RESULTS


@dataclasses.dataclass
class Claim:
    id: str  # letters only (becomes a LaTeX macro name)
    source: str  # path relative to results/
    get: Callable[[Any], float | int | str]
    fmt: str = "{:.2f}"
    desc: str = ""


def _d(j: dict) -> Any:
    return j.get("data", j)


CLAIMS: list[Claim] = []


def claim(id: str, source: str, fmt: str = "{:.2f}", desc: str = ""):
    def deco(fn):
        CLAIMS.append(Claim(id, source, fn, fmt, desc))
        return fn

    return deco


def register_all() -> None:
    """Import claim definitions (bench/claim_defs.py: M1-M3/M5/M10; bench/claim_defs_ext.py: M4-M9)."""
    import importlib

    for mod in ("bench.claim_defs", "bench.claim_defs_ext"):
        try:
            importlib.import_module(mod)
        except ModuleNotFoundError as e:
            if e.name != mod:
                raise


def evaluate() -> tuple[list[dict], list[str]]:
    register_all()
    out, missing = [], []
    seen = set()
    for c in CLAIMS:
        if not re.fullmatch(r"[A-Za-z]+", c.id) or c.id in seen:
            raise ValueError(f"bad or duplicate claim id {c.id!r}")
        seen.add(c.id)
        p = RESULTS / c.source
        if not p.exists():
            missing.append(f"{c.id}: {c.source} missing")
            continue
        j = json.loads(p.read_text())
        try:
            v = c.get(_d(j))
        except (KeyError, IndexError, TypeError, ValueError) as e:
            missing.append(f"{c.id}: {c.source}: {type(e).__name__}: {e}")
            continue
        text = v if isinstance(v, str) else c.fmt.format(v)
        out.append(
            {
                "id": c.id,
                "value": v,
                "text": text,
                "source": f"results/{c.source}",
                "source_commit": j.get("meta", {}).get("git", {}).get("commit"),
                "desc": c.desc,
            }
        )
    return out, missing


def main() -> int:
    from bench.meta import write_result

    claims, missing = evaluate()
    write_result(RESULTS / "claims.json", {"claims": claims, "missing": missing})
    tex = ["% generated by `python -m bench.claims`; do not edit"]
    for c in claims:
        t = str(c["text"]).replace("%", r"\%")
        tex.append(f"\\newcommand{{\\C{c['id']}}}{{{t}}}  % {c['source']}")
    paper = REPO_ROOT / "paper"
    paper.mkdir(exist_ok=True)
    (paper / "numbers.tex").write_text("\n".join(tex) + "\n")
    print(f"{len(claims)} claims written; {len(missing)} missing")
    for m in missing:
        print("  missing:", m)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
